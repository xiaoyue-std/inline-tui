//! Unicode character display width (wcwidth style).
//!
//! Covers common zero-width characters (combining marks, zero-width spaces,
//! etc.) and double-width characters (CJK, fullwidth, emoji). Width computation
//! is used throughout for wrapping, editor cursors, and diff alignment.

/// Display width of a single character: 0 (zero-width), 1 (normal), 2 (wide).
pub fn char_width(c: char) -> usize {
    let cp = c as u32;
    if cp == 0 {
        return 0;
    }
    // Control characters: excluded from normal layout
    if cp < 0x20 || (0x7F..0xA0).contains(&cp) {
        return 0;
    }
    if is_zero_width(cp) {
        return 0;
    }
    if is_wide(cp) {
        2
    } else {
        1
    }
}

/// Display width of a string.
pub fn str_width(s: &str) -> usize {
    s.chars().map(char_width).sum()
}

/// Truncates a string to a display width (keeps whole characters, never cuts a wide char in half).
pub fn truncate_to_width(s: &str, max: usize) -> String {
    let mut out = String::new();
    let mut w = 0;
    for ch in s.chars() {
        let cw = char_width(ch);
        if w + cw > max {
            break;
        }
        out.push(ch);
        w += cw;
    }
    out
}

fn in_ranges(cp: u32, ranges: &[u32]) -> bool {
    // ranges appear in [start0, end0, start1, end1, ...] pairs
    ranges.chunks(2).any(|r| cp >= r[0] && cp <= r[1])
}

